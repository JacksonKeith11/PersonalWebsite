# Builds Overlords' sprite atlas: every unit, summon and monster in five poses (kit.POSES), 32x32 each,
# one row per sprite, into app/static/games/overlords/art/units.png; the 16x16 icons (items, traits,
# projectiles: icons.py) into art/icons.png; the commander portraits (portraits.py) and the two ground
# tiles into art/portraits.png; and js/atlas.js, which names every cell and carries each PNG's hash
# (Cloudflare caches /static, so a new PNG needs a new URL).
#     python3 tools/overlords-art/build.py
# Never edit units.png or atlas.js by hand. Preview with sheet.py.
import hashlib
import io
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import units1  # noqa: E402
import units2  # noqa: E402
import units3  # noqa: E402
import icons  # noqa: E402
import portraits  # noqa: E402

SPRITES = {}
for _mod in (units1, units2, units3):
    for _name in dir(_mod):
        _f = getattr(_mod, _name)
        if callable(_f) and getattr(_f, '__module__', None) == _mod.__name__ and not _name.startswith('_') \
                and _name not in ("skeleton_fig", "dwarf", "ear", "frog_head"):
            SPRITES[_name] = _f


def main():
    from kit import render, POSES, poses
    root = os.path.normpath(os.path.join(HERE, '..', '..'))
    sys.path.insert(0, root)
    from app.overlords import data as D
    missing = [k for k in D.UNITS if k not in SPRITES]
    if missing:
        print('no sprite for:', ', '.join(missing))
    names = [k for k in D.UNITS if k in SPRITES]
    atlas = Image.new('RGBA', (32 * len(POSES), 32 * len(names)), (0, 0, 0, 0))
    for i, n in enumerate(names):
        rows, pal = SPRITES[n]()
        assert len(rows) == 32 and all(len(r) == 32 for r in rows), n
        for j, (pose, r) in enumerate(poses(rows).items()):
            atlas.alpha_composite(render(r, pal), (32 * j, 32 * i))
    art = os.path.join(root, 'app', 'static', 'games', 'overlords', 'art')
    os.makedirs(art, exist_ok=True)

    def save(img, name):
        buf = io.BytesIO()
        img.save(buf, 'PNG', optimize=True)
        data = buf.getvalue()
        with open(os.path.join(art, name), 'wb') as fh:
            fh.write(data)
        return f'/static/games/overlords/art/{name}?h={hashlib.sha1(data).hexdigest()[:10]}', len(data)

    units_url, size = save(atlas, 'units.png')
    # the icons: 16x16 cells, ICON_COLS to a row
    icon_fns = icons.all_icons()
    missing += [k for k in D.ITEMS if 'item:' + k not in icon_fns]
    missing += [t for t in D.TRAITS if 'trait:' + t not in icon_fns]
    cols = 16
    sheet = Image.new('RGBA', (16 * cols, 16 * ((len(icon_fns) + cols - 1) // cols)), (0, 0, 0, 0))
    icon_at = {}
    for i, (n, f) in enumerate(icon_fns.items()):
        rows, pal = f()
        assert len(rows) == 16 and all(len(r) == 16 for r in rows), n
        sheet.alpha_composite(render(rows, pal), (16 * (i % cols), 16 * (i // cols)))
        icon_at[n] = i
    icons_url, isize = save(sheet, 'icons.png')
    # the portraits, then the ground tiles: 32x32 cells in one row
    missing += [k for k in D.COMMANDERS if k not in portraits.PORTRAITS]
    cells = list(portraits.PORTRAITS.items())
    pics = Image.new('RGBA', (32 * (len(cells) + 2), 32), (0, 0, 0, 0))
    for i, (n, f) in enumerate(cells):
        rows, pal = f()
        pics.alpha_composite(render(rows, pal), (32 * i, 0))
    for j, (base, specks) in enumerate(GROUND):
        pics.paste(ground(base, specks, seed=j), (32 * (len(cells) + j), 0))
    pics_url, psize = save(pics, 'portraits.png')
    js = ('// Generated by tools/overlords-art/build.py: never edit by hand.\n'
          '// Each sprite is a row of the atlas; each pose a 32x32 column, in POSES order. ICONS: 16x16 cells,\n'
          '// ICON_COLS to a row (item:<key>, trait:<key>, proj:<kind>). PORTRAITS: 32x32 cells in one row\n'
          '// (commanders, then the ground tiles GROUND_HOME and GROUND_AWAY).\n'
          f'export const ATLAS_URL = "{units_url}";\n'
          f'export const POSES = {json.dumps(list(POSES))};\n'
          f'export const ROWS = {json.dumps({n: i for i, n in enumerate(names)})};\n'
          f'export const ICONS_URL = "{icons_url}";\n'
          f'export const ICON_COLS = {cols};\n'
          f'export const ICONS = {json.dumps(icon_at)};\n'
          f'export const PORTRAITS_URL = "{pics_url}";\n'
          f'export const PORTRAITS = {json.dumps({n: i for i, (n, _) in enumerate(cells)})};\n'
          f'export const GROUND_HOME = {len(cells)};\n'
          f'export const GROUND_AWAY = {len(cells) + 1};\n')
    with open(os.path.join(root, 'app', 'static', 'games', 'overlords', 'js', 'atlas.js'), 'w') as fh:
        fh.write(js)
    print(f'{len(names)} sprites ({size // 1024} KB), {len(icon_fns)} icons ({isize // 1024} KB), '
          f'{len(cells)} portraits ({psize // 1024} KB)')
    if missing:
        print('missing art for:', ', '.join(missing))
    return missing


# The battlefield's ground: a tileable 32x32 texture for each half (home, away): a base colour and
# specks (colour, how many, tuft or single pixel).
GROUND = [
    ('#2d384e', [('#313d55', 70, False), ('#29334a', 60, False), ('#37455e', 8, True)]),
    ('#282d3e', [('#2c3244', 70, False), ('#252a3a', 60, False), ('#33394e', 8, True)]),
]


def ground(base, specks, seed=0):
    import random
    from kit import hexrgb
    rng = random.Random(seed)
    img = Image.new('RGBA', (32, 32), hexrgb(base) + (255,))
    for color, n, tuft in specks:
        c = hexrgb(color) + (255,)
        for _ in range(n):
            x, y = rng.randrange(32), rng.randrange(32)
            img.putpixel((x, y), c)
            if tuft:
                img.putpixel(((x + 1) % 32, y), c)
                img.putpixel((x, (y + 31) % 32), c)
    return img


if __name__ == '__main__':
    sys.exit(1 if main() else 0)
