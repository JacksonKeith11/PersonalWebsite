# Writes app/static/games/threefold/js/sprites.js from picks.py. Run from this folder: python3 build.py
import importlib, json, os
from picks import PICKS
out = ['// GENERATED by tools/threefold-art/build.py from picks.py. Do not edit by hand: change the Python and rebuild.',
       '// 32x32 sprites as flat colour regions; flat32() in art.js adds the outline and the shading.', 'export const SPRITES = {']
for key, (mod, fn) in PICKS.items():
    g = getattr(importlib.import_module(mod), fn)()
    rows = g.strings()
    used = sorted(set(''.join(rows)) - {'.'})
    missing = [c for c in used if c not in g.pal]
    assert not missing, (key, missing)
    pal = ', '.join(f"{c}: '{g.pal[c]}'" for c in used)
    out.append(f'  {key}: {{ pal: {{ {pal} }}, rows: [')
    out += [f"    '{r}'," for r in rows]
    out.append('  ] },')
out.append('};')
path = os.path.join(os.path.dirname(__file__), '..', '..', 'app', 'static', 'games', 'threefold', 'js', 'sprites.js')
open(path, 'w').write('\n'.join(out) + '\n')
print(f'wrote {len(PICKS)} sprites to {os.path.normpath(path)}')
