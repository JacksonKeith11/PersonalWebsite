"""The archipelago's other islands: eight more regions a run can draw its three objectives from, each with
its own land (`SKINS` here names it; `hexmap.js` paints it), its own map rule (see `game.py`'s biome
section), its own enemies, roaming big threat, dungeon and boss, and events found only there.

Merged into `archipelago.py`'s tables on import (FOES, POOLS, GROUPS, LAIRS, DUNGEONS, BIG, REGION_NAMES,
EVENTS), so everything that reads those works for these regions too. Enemy traits added for these
regions (read in `combat.py` and `bosses.py`): `regen` N (heals N at the start of each round),
`armor_round` N (gains N Armor each round), `ember` N (Burns every hero N when it dies), `aura_heal` N
(the other enemies heal N each round while it stands) and `sleeper` (asleep, doing nothing, until
something hits it). Bloodied rules here are the generic ones in `Bosses.bloodied_rule`: `summon` (a new
enemy each round), `thorns` (whoever hits it takes more, growing with `grow`), `curse` (a status on
heroes every `every` rounds), `fall` (a hero is marked each round and takes a blow at its end unless
Armor or a Guard stops it), `ward` (half damage while one of `by` stands) and `regen`.
"""


