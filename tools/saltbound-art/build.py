# Writes app/static/games/saltbound/js/sprites.js from PICKS. Run from this folder: python3 build.py
# To change a hero's look, point its entry at another option in heroes.py and rebuild.
import json, os
import heroes, heroes2, foes
PICKS = {
    'vanguard': heroes.vanguard1, 'arcanist': heroes.arcanist2, 'mender': heroes.mender1,  # the owner's picks
    # build step 2's classes: option 1 of each until the owner picks (see heroes2.OPTIONS)
    **{cls: opts[0][1] for cls, opts in heroes2.OPTIONS.items()},
    **{f.__name__: f for f in foes.ALL},
    **{f.__name__: f for f in foes.SUMMONS},
}
out = ['// GENERATED by tools/saltbound-art/build.py. Do not edit by hand: change the Python and rebuild.',
       '// 32x32 sprites as flat colour regions; flat32() in art.js adds the outline and the shading.', 'export const SPRITES = {']
for key, fn in PICKS.items():
    g = fn()
    rows = g.strings()
    used = sorted(set(''.join(rows)) - {'.'})
    missing = [c for c in used if c not in g.pal]
    assert not missing, (key, missing)
    pal = ', '.join(f"{c}: '{g.pal[c]}'" for c in used)
    out.append(f'  {key}: {{ pal: {{ {pal} }}, rows: [')
    out += [f"    '{r}'," for r in rows]
    out.append('  ] },')
out.append('};')
path = os.path.join(os.path.dirname(__file__), '..', '..', 'app', 'static', 'games', 'saltbound', 'js', 'sprites.js')
os.makedirs(os.path.dirname(path), exist_ok=True)
open(path, 'w').write('\n'.join(out) + '\n')
print(f'wrote {len(PICKS)} sprites to {os.path.normpath(path)}')
